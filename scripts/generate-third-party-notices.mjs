// Writes THIRD_PARTY_NOTICES.md: the license text of every npm package whose code ends up in the
// shipped app (package.json `dependencies` plus their runtime dependency trees, and the UI libraries
// that the renderer bundle contains). Run with `npm run notices` after changing dependencies.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'))

// Renderer-only libraries are devDependencies (Vite compiles them into the renderer bundle), so
// they have to be named here. Build tools (tailwindcss, vite, electron-builder, ...) ship no code.
const RENDERER_BUNDLED = [
  'react',
  'react-dom',
  '@tanstack/react-query',
  'class-variance-authority',
  'clsx',
  'lucide-react',
  'tailwind-merge',
  ...Object.keys(pkg.devDependencies).filter((n) => n.startsWith('@radix-ui/'))
]
const roots = [...new Set([...Object.keys(pkg.dependencies), ...RENDERER_BUNDLED])]

function findPackageDir(name, fromDir) {
  for (let dir = fromDir; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, 'node_modules', name)
    if (fs.existsSync(path.join(candidate, 'package.json'))) return candidate
    if (dir === path.dirname(dir)) return null
  }
}

const found = new Map() // "name@version" -> entry
function visit(name, fromDir) {
  const dir = findPackageDir(name, fromDir)
  if (!dir) return
  const meta = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'))
  const key = `${meta.name}@${meta.version}`
  if (found.has(key)) return
  const licenseFile = fs
    .readdirSync(dir)
    .find((f) => /^(licen[sc]e|copying)(\.(md|txt))?$/i.test(f))
  const license =
    typeof meta.license === 'string' ? meta.license : (meta.license?.type ?? 'see package')
  found.set(key, {
    name: meta.name,
    version: meta.version,
    license,
    homepage: meta.homepage ?? meta.repository?.url ?? meta.repository ?? '',
    text: licenseFile ? fs.readFileSync(path.join(dir, licenseFile), 'utf8').trim() : null
  })
  for (const dep of Object.keys(meta.dependencies ?? {})) visit(dep, dir)
}
for (const name of roots) visit(name, root)

const entries = [...found.values()].sort((a, b) => a.name.localeCompare(b.name))
const header = `# Third-party notices

Cloudflared Tunnel GUI is released under the MIT License (see \`LICENSE\`). It includes the open-source
software listed below, each under its own license.

- **Electron and Chromium** are part of every build. Their licenses are shipped alongside the
  application as \`LICENSE.electron.txt\` and \`LICENSES.chromium.html\`.
- **cloudflared** is not part of this application. It is a separate program from Cloudflare, Inc.
  (Apache License 2.0). The app can download the official release and uses it as a command-line tool.

This file is generated by \`npm run notices\`.

---
`

const body = entries
  .map((e) => {
    const link = typeof e.homepage === 'string' && e.homepage ? `\n${e.homepage}` : ''
    const text = e.text
      ? `\n\n\`\`\`text\n${e.text}\n\`\`\``
      : `\n\nNo license file is included in this package; it is declared as ${e.license}.`
    return `## ${e.name} ${e.version} (${e.license})${link}${text}`
  })
  .join('\n\n')

fs.writeFileSync(path.join(root, 'THIRD_PARTY_NOTICES.md'), `${header}\n${body}\n`)

const byLicense = entries.reduce(
  (acc, e) => ({ ...acc, [e.license]: (acc[e.license] ?? 0) + 1 }),
  {}
)
const missing = entries.filter((e) => !e.text).map((e) => `${e.name}@${e.version}`)
console.log(`Wrote THIRD_PARTY_NOTICES.md: ${entries.length} packages`, byLicense)
if (missing.length) console.log('No license file in:', missing.join(', '))
